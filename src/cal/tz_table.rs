/// A Windows id written as the TZID (Outlook), as the table spells it.
pub fn windows_id(id: &str) -> Option<&'static str> {
    WINDOWS
        .binary_search(&id)
        .ok()
        .and_then(|i| WINDOWS.get(i))
        .copied()
}

/// The Windows id of an IANA name.
pub fn iana(id: &str) -> Option<&'static str> {
    let i = IANA.binary_search_by(|(n, _)| (*n).cmp(id)).ok()?;
    let (_, w) = IANA.get(i)?;
    WINDOWS.get(usize::from(*w)).copied()
}

#[cfg(test)]
#[allow(clippy::indexing_slicing)]
mod tests {
    use super::*;

    #[test]
    fn sorted_and_in_range() {
        assert!(WINDOWS.windows(2).all(|w| w[0] < w[1]));
        assert!(IANA.windows(2).all(|w| w[0].0 < w[1].0));
        assert!(IANA.iter().all(|(_, i)| usize::from(*i) < WINDOWS.len()));
        assert_eq!(iana("Europe/Lisbon"), Some("GMT Standard Time"));
        assert_eq!(iana("America/New_York"), Some("Eastern Standard Time"));
        assert_eq!(
            windows_id("Tokyo Standard Time"),
            Some("Tokyo Standard Time")
        );
        assert_eq!(iana("Nowhere/Else"), None);
    }
}
