# Writes src/cal/tz_table.rs from a downloaded CLDR windowsZones.xml
# (https://github.com/unicode-org/cldr/blob/main/common/supplemental/windowsZones.xml).
# Run by hand, never in CI:
#   pwsh scripts/gen-tz-table.ps1 path\to\windowsZones.xml
# Every mapZone entry is used (every territory, not only 001), so
# Europe/Lisbon maps to "GMT Standard Time" through territory PT.
param([Parameter(Mandatory = $true)][string]$Xml)

$ErrorActionPreference = 'Stop'
[xml]$doc = Get-Content -LiteralPath $Xml -Raw
$pairs = @{}
foreach ($z in $doc.supplementalData.windowsZones.mapTimezones.mapZone) {
    foreach ($name in ($z.type -split ' ')) {
        if ($name -and -not $pairs.ContainsKey($name)) { $pairs[$name] = $z.other }
    }
}
$ord = [StringComparer]::Ordinal
$windows = [string[]]($pairs.Values | Sort-Object -Unique)
[Array]::Sort($windows, $ord)
$names = [string[]]$pairs.Keys
[Array]::Sort($names, $ord)
$rev = $doc.supplementalData.version.number
$out = New-Object System.Text.StringBuilder
[void]$out.AppendLine("//! IANA time zone names to Windows ids, from CLDR windowsZones.xml ($rev),")
[void]$out.AppendLine('//! every mapZone entry. Generated by scripts/gen-tz-table.ps1; do not edit.')
[void]$out.AppendLine('')
[void]$out.AppendLine('/// The Windows ids the table names, sorted.')
[void]$out.AppendLine('const WINDOWS: &[&str] = &[')
foreach ($w in $windows) { [void]$out.AppendLine("    `"$w`",") }
[void]$out.AppendLine('];')
[void]$out.AppendLine('')
[void]$out.AppendLine('/// (IANA name, index into [`WINDOWS`]), sorted by name.')
[void]$out.AppendLine('const IANA: &[(&str, u8)] = &[')
foreach ($n in $names) {
    $i = [Array]::BinarySearch($windows, $pairs[$n], $ord)
    [void]$out.AppendLine("    (`"$n`", $i),")
}
[void]$out.AppendLine('];')
$table = Join-Path $PSScriptRoot '..\src\cal\tz_table.rs'
# Keep the lookup functions and tests after the tables.
$old = Get-Content -LiteralPath $table -Raw
$tail = $old.Substring($old.IndexOf('/// A Windows id written as the TZID'))
[void]$out.AppendLine('')
[void]$out.Append($tail)
Set-Content -LiteralPath $table -Value $out.ToString() -NoNewline -Encoding utf8NoBOM
