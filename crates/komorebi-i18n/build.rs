//! Turns every `translations/<tag>/LC_MESSAGES/komorebi.po` into a static
//! table (`$OUT_DIR/catalogs.rs`): one sorted slice of entries per language,
//! keyed by (msgctxt, msgid), with the language's plural rule. Fuzzy and
//! untranslated entries are left out, so the source text shows; the rules
//! that make a catalog shippable (complete, current, no fuzzy, placeholders,
//! glossary) are `tests/i18n_catalog.rs`'s, not the build's.

#[path = "po.rs"]
mod po;

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::PathBuf;

fn main() {
    let manifest = PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").expect("Cargo sets it"));
    let translations = manifest.join("..").join("..").join("translations");
    println!("cargo::rerun-if-changed=po.rs");
    println!("cargo::rerun-if-changed={}", translations.display());

    let mut dirs: Vec<PathBuf> = std::fs::read_dir(&translations)
        .unwrap_or_else(|e| panic!("reading {}: {e}", translations.display()))
        .map(|e| e.expect("a directory entry").path())
        .filter(|p| p.join("LC_MESSAGES").join("komorebi.po").is_file())
        .collect();
    dirs.sort();

    let mut out = String::from(
        "// Generated by build.rs from translations/<tag>/LC_MESSAGES/komorebi.po.\n\
         pub(crate) static CATALOGS: &[Catalog] = &[\n",
    );
    for dir in dirs {
        let tag = dir
            .file_name()
            .and_then(|n| n.to_str())
            .expect("a UTF-8 folder name")
            .to_string();
        let path = dir.join("LC_MESSAGES").join("komorebi.po");
        println!("cargo::rerun-if-changed={}", path.display());
        let text = std::fs::read_to_string(&path)
            .unwrap_or_else(|e| panic!("reading {}: {e}", path.display()))
            .replace("\r\n", "\n");
        let catalog = po::parse_po(&text);
        let plural =
            po::plural_rule(&catalog.header).unwrap_or_else(|e| panic!("{}: {e}", path.display()));

        // (ctx, id) -> forms; BTreeMap order is the order the lookup's
        // binary search expects (None before Some, then byte order).
        let mut table: BTreeMap<(Option<String>, String), Vec<String>> = BTreeMap::new();
        for entry in catalog.entries {
            let msg = entry.msg.expect("parse_po sets it");
            let wanted = if msg.plural.is_some() {
                entry.strs.len().max(2)
            } else {
                1
            };
            let forms: Vec<String> = (0..wanted)
                .map(|i| entry.strs.get(&i).cloned().unwrap_or_default())
                .collect();
            if entry.fuzzy || forms.iter().any(String::is_empty) {
                continue;
            }
            let key = (msg.ctx, msg.id);
            assert!(
                !table.contains_key(&key),
                "{}: {:?} appears twice (line {})",
                path.display(),
                key,
                entry.line
            );
            table.insert(key, forms);
        }

        writeln!(
            out,
            "    Catalog {{ tag: {tag:?}, plural: Plural::{plural}, entries: &["
        )
        .unwrap();
        for ((ctx, id), forms) in table {
            write!(out, "        E {{ c: {ctx:?}, i: {id:?}, f: &[").unwrap();
            for form in forms {
                write!(out, "{form:?}, ").unwrap();
            }
            out.push_str("] },\n");
        }
        out.push_str("    ] },\n");
    }
    out.push_str("];\n");

    let dest =
        PathBuf::from(std::env::var_os("OUT_DIR").expect("Cargo sets it")).join("catalogs.rs");
    std::fs::write(&dest, out).unwrap_or_else(|e| panic!("writing {}: {e}", dest.display()));
}
