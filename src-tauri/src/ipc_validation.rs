use std::{error::Error, fmt};

use url::Url;

pub const MAX_IPC_PAYLOAD_BYTES: usize = 1024 * 1024;
pub const MAX_TEXT_FIELD_BYTES: usize = 64 * 1024;
pub const MAX_URL_BYTES: usize = 2048;
pub const MAX_ID_BYTES: usize = 128;

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum IpcValidationError {
    EmptyField {
        field: &'static str,
    },
    OversizedPayload {
        field: &'static str,
        max_bytes: usize,
        actual_bytes: usize,
    },
    ClientSuppliedPath {
        field: &'static str,
    },
    RawSql {
        field: &'static str,
    },
    UnsafeUrl {
        field: &'static str,
        reason: &'static str,
    },
    UnsanitizedHtml {
        field: &'static str,
        reason: &'static str,
    },
    InvalidId {
        field: &'static str,
        reason: &'static str,
    },
    UnknownAccount,
    UnknownFolder,
    UnknownMessage,
}

impl fmt::Display for IpcValidationError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::EmptyField { field } => write!(formatter, "{field} is required"),
            Self::OversizedPayload {
                field,
                max_bytes,
                actual_bytes,
            } => write!(
                formatter,
                "{field} exceeds {max_bytes} bytes ({actual_bytes} bytes provided)"
            ),
            Self::ClientSuppliedPath { field } => {
                write!(formatter, "{field} must be generated by the backend")
            }
            Self::RawSql { field } => write!(formatter, "{field} must not contain raw SQL"),
            Self::UnsafeUrl { field, reason } => {
                write!(formatter, "{field} URL rejected: {reason}")
            }
            Self::UnsanitizedHtml { field, reason } => {
                write!(formatter, "{field} contains unsanitized HTML: {reason}")
            }
            Self::InvalidId { field, reason } => write!(formatter, "{field} is invalid: {reason}"),
            Self::UnknownAccount => write!(formatter, "account was not found"),
            Self::UnknownFolder => write!(formatter, "folder was not found for account"),
            Self::UnknownMessage => write!(formatter, "message was not found for folder"),
        }
    }
}

impl Error for IpcValidationError {}

pub fn validate_payload_size(
    field: &'static str,
    value: &[u8],
    max_bytes: usize,
) -> Result<(), IpcValidationError> {
    if value.len() > max_bytes {
        return Err(IpcValidationError::OversizedPayload {
            field,
            max_bytes,
            actual_bytes: value.len(),
        });
    }

    Ok(())
}

pub fn validate_bounded_text(
    field: &'static str,
    value: &str,
    max_bytes: usize,
) -> Result<(), IpcValidationError> {
    if value.trim().is_empty() {
        return Err(IpcValidationError::EmptyField { field });
    }

    validate_payload_size(field, value.as_bytes(), max_bytes)
}

pub fn reject_client_supplied_path(
    field: &'static str,
    value: &str,
) -> Result<(), IpcValidationError> {
    if value.trim().is_empty() {
        return Err(IpcValidationError::EmptyField { field });
    }

    Err(IpcValidationError::ClientSuppliedPath { field })
}

pub fn reject_raw_sql(field: &'static str, value: &str) -> Result<(), IpcValidationError> {
    validate_bounded_text(field, value, MAX_TEXT_FIELD_BYTES)?;

    if looks_like_sql(value) {
        return Err(IpcValidationError::RawSql { field });
    }

    Ok(())
}

pub fn validate_checked_url(field: &'static str, value: &str) -> Result<Url, IpcValidationError> {
    validate_bounded_text(field, value, MAX_URL_BYTES)?;

    let parsed = Url::parse(value).map_err(|_| IpcValidationError::UnsafeUrl {
        field,
        reason: "absolute http or https URL required",
    })?;

    match parsed.scheme() {
        "http" | "https" => {}
        _ => {
            return Err(IpcValidationError::UnsafeUrl {
                field,
                reason: "only http and https URLs are allowed",
            })
        }
    }

    if parsed.host_str().is_none() {
        return Err(IpcValidationError::UnsafeUrl {
            field,
            reason: "host is required",
        });
    }

    if !parsed.username().is_empty() || parsed.password().is_some() {
        return Err(IpcValidationError::UnsafeUrl {
            field,
            reason: "embedded credentials are not allowed",
        });
    }

    Ok(parsed)
}

pub fn reject_unsanitized_html(field: &'static str, value: &str) -> Result<(), IpcValidationError> {
    validate_bounded_text(field, value, MAX_TEXT_FIELD_BYTES)?;

    let lowered = value.to_ascii_lowercase();
    let has_markup = lowered.contains('<') || lowered.contains('>');
    let has_script_url = lowered.contains("javascript:");
    let has_inline_event = lowered.contains(" on") && lowered.contains('=');

    if has_markup {
        return Err(IpcValidationError::UnsanitizedHtml {
            field,
            reason: "raw markup is not accepted by IPC commands",
        });
    }

    if has_script_url {
        return Err(IpcValidationError::UnsanitizedHtml {
            field,
            reason: "script URLs are not allowed",
        });
    }

    if has_inline_event {
        return Err(IpcValidationError::UnsanitizedHtml {
            field,
            reason: "inline event handlers are not allowed",
        });
    }

    Ok(())
}

pub fn validate_entity_id(field: &'static str, value: &str) -> Result<(), IpcValidationError> {
    validate_bounded_text(field, value, MAX_ID_BYTES)?;

    if !value
        .bytes()
        .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'-' | b'_'))
    {
        return Err(IpcValidationError::InvalidId {
            field,
            reason: "only ASCII letters, digits, hyphen, and underscore are allowed",
        });
    }

    Ok(())
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct MessageScopeRequest<'a> {
    pub account_id: &'a str,
    pub folder_id: &'a str,
    pub message_id: &'a str,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ValidatedMessageScope<'a> {
    pub account_id: &'a str,
    pub folder_id: &'a str,
    pub message_id: &'a str,
}

pub trait EntityLookup {
    fn account_exists(&self, account_id: &str) -> bool;
    fn folder_belongs_to_account(&self, account_id: &str, folder_id: &str) -> bool;
    fn message_belongs_to_folder(
        &self,
        account_id: &str,
        folder_id: &str,
        message_id: &str,
    ) -> bool;
}

pub fn validate_message_scope<'a>(
    request: MessageScopeRequest<'a>,
    lookup: &impl EntityLookup,
) -> Result<ValidatedMessageScope<'a>, IpcValidationError> {
    validate_entity_id("account_id", request.account_id)?;
    validate_entity_id("folder_id", request.folder_id)?;
    validate_entity_id("message_id", request.message_id)?;

    if !lookup.account_exists(request.account_id) {
        return Err(IpcValidationError::UnknownAccount);
    }

    if !lookup.folder_belongs_to_account(request.account_id, request.folder_id) {
        return Err(IpcValidationError::UnknownFolder);
    }

    if !lookup.message_belongs_to_folder(request.account_id, request.folder_id, request.message_id)
    {
        return Err(IpcValidationError::UnknownMessage);
    }

    Ok(ValidatedMessageScope {
        account_id: request.account_id,
        folder_id: request.folder_id,
        message_id: request.message_id,
    })
}

fn looks_like_sql(value: &str) -> bool {
    if value.contains(';') || value.contains("--") || value.contains("/*") {
        return true;
    }

    let mut normalized = String::with_capacity(value.len());
    for character in value.chars() {
        if character.is_ascii_alphanumeric() || character == '_' {
            normalized.push(character.to_ascii_uppercase());
        } else {
            normalized.push(' ');
        }
    }

    let mut tokens = normalized.split_whitespace();
    let first = tokens.next();
    let second = tokens.next();

    matches!(
        first,
        Some(
            "ALTER"
                | "ATTACH"
                | "CREATE"
                | "DELETE"
                | "DETACH"
                | "DROP"
                | "INSERT"
                | "PRAGMA"
                | "REPLACE"
                | "SELECT"
                | "UPDATE"
                | "VACUUM"
        )
    ) || matches!((first, second), (Some("WITH"), Some(_)))
}

#[cfg(test)]
mod tests {
    use super::*;

    struct FakeLookup;

    impl EntityLookup for FakeLookup {
        fn account_exists(&self, account_id: &str) -> bool {
            account_id == "acct_1"
        }

        fn folder_belongs_to_account(&self, account_id: &str, folder_id: &str) -> bool {
            account_id == "acct_1" && folder_id == "folder_1"
        }

        fn message_belongs_to_folder(
            &self,
            account_id: &str,
            folder_id: &str,
            message_id: &str,
        ) -> bool {
            account_id == "acct_1" && folder_id == "folder_1" && message_id == "msg_1"
        }
    }

    #[test]
    fn rejects_client_supplied_paths() {
        for path in [
            "C:\\Users\\Alice\\mail.db",
            "\\\\server\\share\\mail.db",
            "..\\AppData\\Local\\Komorebi\\mail.db",
            "attachments/message.pdf",
        ] {
            assert_eq!(
                reject_client_supplied_path("local_path", path),
                Err(IpcValidationError::ClientSuppliedPath {
                    field: "local_path"
                })
            );
        }
    }

    #[test]
    fn rejects_raw_sql_payloads() {
        for sql in [
            "SELECT * FROM messages",
            "insert into accounts values (1)",
            "UPDATE messages SET seen = 1",
            "DELETE FROM folders",
            "DROP TABLE messages",
            "PRAGMA table_info(messages)",
            "WITH rows AS (SELECT 1) SELECT * FROM rows",
            "subject; DELETE FROM messages",
        ] {
            assert_eq!(
                reject_raw_sql("query", sql),
                Err(IpcValidationError::RawSql { field: "query" })
            );
        }

        assert_eq!(reject_raw_sql("query", "komorebi inbox search"), Ok(()));
    }

    #[test]
    fn validates_checked_http_urls() {
        assert_eq!(
            validate_checked_url("link", "javascript:alert(1)").unwrap_err(),
            IpcValidationError::UnsafeUrl {
                field: "link",
                reason: "only http and https URLs are allowed"
            }
        );
        assert!(validate_checked_url("link", "file:///C:/Windows/win.ini").is_err());
        assert!(validate_checked_url("link", "data:text/html,<script>").is_err());
        assert!(validate_checked_url("link", "mailto:person@example.com").is_err());
        assert!(validate_checked_url("link", "https://user:pass@example.com").is_err());
        assert!(validate_checked_url("link", "https://example.com/message").is_ok());
    }

    #[test]
    fn rejects_unsanitized_html() {
        for html in [
            "<p>hello</p>",
            "<script>alert(1)</script>",
            "<img src=x onerror=alert(1)>",
            "<a href=\"javascript:alert(1)\">open</a>",
        ] {
            assert!(matches!(
                reject_unsanitized_html("body_html", html),
                Err(IpcValidationError::UnsanitizedHtml { .. })
            ));
        }

        assert_eq!(
            reject_unsanitized_html("body_text", "plain body text"),
            Ok(())
        );
    }

    #[test]
    fn rejects_unbounded_payloads() {
        let oversized = vec![0_u8; MAX_IPC_PAYLOAD_BYTES + 1];

        assert_eq!(
            validate_payload_size("payload", &oversized, MAX_IPC_PAYLOAD_BYTES),
            Err(IpcValidationError::OversizedPayload {
                field: "payload",
                max_bytes: MAX_IPC_PAYLOAD_BYTES,
                actual_bytes: MAX_IPC_PAYLOAD_BYTES + 1
            })
        );
    }

    #[test]
    fn validates_account_folder_message_scope() {
        let lookup = FakeLookup;

        assert_eq!(
            validate_message_scope(
                MessageScopeRequest {
                    account_id: "acct_1",
                    folder_id: "folder_1",
                    message_id: "msg_1",
                },
                &lookup,
            ),
            Ok(ValidatedMessageScope {
                account_id: "acct_1",
                folder_id: "folder_1",
                message_id: "msg_1",
            })
        );

        assert_eq!(
            validate_message_scope(
                MessageScopeRequest {
                    account_id: "acct_missing",
                    folder_id: "folder_1",
                    message_id: "msg_1",
                },
                &lookup,
            ),
            Err(IpcValidationError::UnknownAccount)
        );
        assert_eq!(
            validate_message_scope(
                MessageScopeRequest {
                    account_id: "acct_1",
                    folder_id: "folder_missing",
                    message_id: "msg_1",
                },
                &lookup,
            ),
            Err(IpcValidationError::UnknownFolder)
        );
        assert_eq!(
            validate_message_scope(
                MessageScopeRequest {
                    account_id: "acct_1",
                    folder_id: "folder_1",
                    message_id: "msg_missing",
                },
                &lookup,
            ),
            Err(IpcValidationError::UnknownMessage)
        );
    }

    #[test]
    fn rejects_invalid_entity_ids_before_lookup() {
        let lookup = FakeLookup;

        assert_eq!(
            validate_message_scope(
                MessageScopeRequest {
                    account_id: "acct_1/../../secrets",
                    folder_id: "folder_1",
                    message_id: "msg_1",
                },
                &lookup,
            ),
            Err(IpcValidationError::InvalidId {
                field: "account_id",
                reason: "only ASCII letters, digits, hyphen, and underscore are allowed"
            })
        );
    }

    #[test]
    fn validation_errors_do_not_echo_sensitive_values() {
        let secret = "acct_secret@example.com";
        let error = validate_message_scope(
            MessageScopeRequest {
                account_id: secret,
                folder_id: "folder_1",
                message_id: "msg_1",
            },
            &FakeLookup,
        )
        .unwrap_err()
        .to_string();

        assert!(!error.contains(secret));
    }
}
